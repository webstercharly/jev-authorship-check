#!/usr/bin/env python3
"""A small Jev experiment for classifying text as human, AI, or uncertain."""

import argparse
import json
import os
import sys
import urllib.error
import urllib.request

API_URL = "https://api.typesafe.ai/v1/systemone"
OPTIONS = {
    "human": "Written primarily by a person",
    "ai_generated": "Written primarily by an AI system",
    "uncertain": "There is not enough evidence to make a confident call",
}


def request_jev(text: str, api_key: str) -> dict:
    payload = {
        "model": "jev-latest",
        "state": text,
        "questions": {
            "authorship": {
                "type": "choice",
                "instructions": (
                    "How likely is it that this text was primarily generated by an AI system? "
                    "Use uncertain when the text may have been edited, is too short, or the evidence is weak."
                ),
                "criteria": OPTIONS,
            }
        },
    }
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        API_URL,
        data=body,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def print_result(result: dict) -> None:
    answer = result["answers"]["authorship"]
    output = {
        "label": answer.get("choice"),
        "confidence": answer.get("confidence"),
        "probabilities": answer.get("probabilities"),
        "model": result.get("model"),
    }
    print(json.dumps(output, indent=2))


def read_text(path: str | None) -> str:
    if path:
        with open(path, encoding="utf-8") as file:
            return file.read()
    if not sys.stdin.isatty():
        return sys.stdin.read()
    raise ValueError("Pass a text file or pipe text on stdin")


def main() -> int:
    parser = argparse.ArgumentParser(description="Try Jev as a lightweight AI-authorship classifier")
    parser.add_argument("file", nargs="?", help="text file to classify; stdin is used when omitted")
    args = parser.parse_args()

    try:
        text = read_text(args.file).strip()
        if not text:
            raise ValueError("The input text is empty")
        api_key = os.environ.get("TYPESAFE_API_KEY")
        if not api_key:
            raise ValueError("Set TYPESAFE_API_KEY before making a Jev request")
        print_result(request_jev(text, api_key))
    except (OSError, ValueError, urllib.error.HTTPError, urllib.error.URLError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
